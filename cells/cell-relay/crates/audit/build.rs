//! Generates the Rust view of the cross-cell contracts (TI-02 AC 5).
//!
//! `contracts/*.vN.json` is the source of truth; `contracts/manifest.json`
//! registers which version of each family is current. Cargo re-runs this
//! whenever a schema or the manifest changes, so the Rust types cannot drift
//! from the schemas the other cells validate with — and nobody hand-writes
//! them, which is the point.

use std::env;
use std::fs::File;
use std::path::PathBuf;

use serde::Deserialize;

#[derive(Deserialize)]
struct Manifest {
    contracts: Vec<ContractEntry>,
}

#[derive(Deserialize)]
struct ContractEntry {
    name: String,
    version: u32,
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR")?);
    // crates/audit → crates → cell-relay → cells → repo root.
    let contracts_dir = manifest_dir
        .join("..")
        .join("..")
        .join("..")
        .join("..")
        .join("contracts");
    let out_dir = PathBuf::from(env::var("OUT_DIR")?);

    let manifest_path = contracts_dir.join("manifest.json");
    println!("cargo:rerun-if-changed={}", manifest_path.display());
    let manifest: Manifest = serde_json::from_reader(File::open(&manifest_path)?)?;

    let mut generated =
        String::from("// Generated by build.rs from contracts/*.vN.json — do not edit.\n");
    for entry in &manifest.contracts {
        let schema_path = contracts_dir.join(format!("{}.v{}.json", entry.name, entry.version));
        println!("cargo:rerun-if-changed={}", schema_path.display());

        let mut schema: serde_json::Value = serde_json::from_reader(File::open(&schema_path)?)?;
        // Generate structural types; conditional relationships are checked by
        // credential_wire at the native boundary, matching ajv's frozen schema.
        // Do not depend on typify interpreting JSON Schema if/then branches.
        if entry.name == "credential_event" {
            if let Some(object) = schema.as_object_mut() {
                object.remove("allOf");
            }
            schema["properties"]["ts"]
                .as_object_mut()
                .ok_or("missing timestamp")?
                .remove("pattern");
        }
        let mut settings = typify::TypeSpaceSettings::default();
        if entry.name == "credential_event"
            || entry.name == "finding"
            || entry.name == "investigation_completion"
            || entry.name == "peer_observation"
        {
            settings.with_conversion(
                serde_json::from_value(schema["properties"]["version"].clone())?,
                if entry.name == "finding" {
                    "crate::finding_wire::Version"
                } else {
                    "crate::investigation_wire::Version"
                },
                std::iter::empty(),
            );
            for properties in [
                &schema["properties"],
                &schema["$defs"]["citation"]["properties"],
            ] {
                if let Some(properties) = properties.as_object() {
                    for value in properties.values() {
                        if value["type"] == "string"
                            && value["minLength"] == 1
                            && let Some(cap) = value["maxLength"].as_u64()
                        {
                            settings.with_conversion(
                                serde_json::from_value(value.clone())?,
                                format!("crate::finding_wire::Text<{cap}>"),
                                std::iter::empty(),
                            );
                        }
                    }
                }
            }
        }
        if entry.name == "source_repair_evidence" {
            source_repair_text(&mut settings, &schema)?;
            settings.with_conversion(
                serde_json::from_value(schema["properties"]["version"].clone())?,
                "crate::profile_wire::ProfileVersion",
                std::iter::empty(),
            );
        }
        if matches!(entry.name.as_str(), "dashboard_query" | "dashboard_read") {
            dashboard_text(&mut settings, &schema)?;
        }
        if entry.name == "credential_event" {
            settings.with_conversion(
                serde_json::from_value(schema["properties"]["ts"].clone())?,
                "crate::credential_wire::UtcTimestamp",
                std::iter::empty(),
            );
        }
        if entry.name == "investigation_job" {
            // Typify prints adjacent length checks on one line. Reuse the
            // checked identifier adapter rather than weakening generated lints.
            for (property, target) in [
                ("tenant", "crate::profile_wire::ProfileIdentifier"),
                ("ceiling", "crate::investigation_wire::Amount"),
                ("version", "crate::investigation_wire::Version"),
            ] {
                settings.with_conversion(
                    serde_json::from_value(schema["properties"][property].clone())?,
                    target,
                    std::iter::empty(),
                );
            }
        }
        if entry.name == "field_profile" || entry.name == "profile_snapshot" {
            let profile = if entry.name == "profile_snapshot" {
                &schema["properties"]["profile"]
            } else {
                &schema
            };
            // Preserve frozen validation: serde lacks [T; 64], and typify's
            // pattern newtype requires regex initialization via unwrap().
            for path in ["/properties/hll", "/properties/values"] {
                let array = profile
                    .pointer(path)
                    .ok_or("missing profile array schema")?;
                settings.with_conversion(
                    serde_json::from_value(array.clone())?,
                    "crate::profile_wire::FixedArray<i64, 64>",
                    std::iter::empty(),
                );
            }
            settings.with_conversion(
                serde_json::from_value(profile["properties"]["version"].clone())?,
                "crate::profile_wire::ProfileVersion",
                std::iter::empty(),
            );
            // Constrained identifier newtypes otherwise emit adjacent `if`s
            // on one generated line, triggering possible_missing_else.
            settings.with_conversion(
                serde_json::from_value(profile["properties"]["window_id"].clone())?,
                "crate::profile_wire::ProfileIdentifier",
                std::iter::empty(),
            );
            let pointer = profile
                .pointer("/properties/scope/properties/field")
                .ok_or("missing profile pointer schema")?;
            settings.with_conversion(
                serde_json::from_value(pointer.clone())?,
                "crate::profile_wire::JsonPointer",
                std::iter::empty(),
            );
        }
        let mut type_space = typify::TypeSpace::new(&settings);
        type_space.add_root_schema(serde_json::from_value(schema)?)?;

        // One module per contract: the schemas share `$defs` names (`Drift`,
        // `Change`), which would collide in a single namespace.
        generated.push_str(&format!("pub mod {} {{\n", entry.name));
        generated.push_str(&type_space.to_stream().to_string());
        generated.push_str("}\n");
    }

    std::fs::write(out_dir.join("contracts.rs"), generated)?;
    Ok(())
}

// Recursively preserve bounded evidence text without typify's adjacent-if checks.
fn dashboard_text(
    settings: &mut typify::TypeSpaceSettings,
    value: &serde_json::Value,
) -> Result<(), Box<dyn std::error::Error>> {
    if value["type"] == "string"
        && value["minLength"] == 1
        && let Some(cap) = value["maxLength"].as_u64()
    {
        let target = if value["pattern"].is_string() {
            "crate::dashboard_wire::Search".to_string()
        } else {
            format!("crate::finding_wire::Text<{cap}>")
        };
        settings.with_conversion(
            serde_json::from_value(value.clone())?,
            target,
            std::iter::empty(),
        );
    }
    match value {
        serde_json::Value::Object(properties) => {
            for child in properties.values() {
                dashboard_text(settings, child)?;
            }
        }
        serde_json::Value::Array(items) => {
            for child in items {
                dashboard_text(settings, child)?;
            }
        }
        _ => {}
    }
    Ok(())
}

// Map every constrained source-repair string without generated regex initialization.
fn source_repair_text(
    settings: &mut typify::TypeSpaceSettings,
    value: &serde_json::Value,
) -> Result<(), Box<dyn std::error::Error>> {
    let target = match value["pattern"].as_str() {
        Some("^[A-Za-z0-9_.:-]+$") => Some("crate::dashboard_wire::Search"),
        Some("^/[A-Za-z_][A-Za-z0-9_]*$") => Some("crate::source_repair_wire::Field"),
        Some("^[a-f0-9]{64}$") => Some("crate::source_repair_wire::Digest"),
        _ => None,
    };
    if let Some(target) = target {
        settings.with_conversion(
            serde_json::from_value(value.clone())?,
            target,
            std::iter::empty(),
        );
    }
    match value {
        serde_json::Value::Object(properties) => {
            for child in properties.values() {
                source_repair_text(settings, child)?;
            }
        }
        serde_json::Value::Array(items) => {
            for child in items {
                source_repair_text(settings, child)?;
            }
        }
        _ => {}
    }
    Ok(())
}
